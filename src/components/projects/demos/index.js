import { lazy } from 'react';

// 📁 راهنمای اضافه کردن یک پروژه جدید به گالری نمونه‌کارها:
//
// ۱. یه پوشه جدید بساز: src/components/projects/demos/<اسم-پروژه>/
//    مثلاً: src/components/projects/demos/project-3/
//
// ۲. داخلش یه کامپوننت React بساز که کل UI پروژه رو نشون بده (index.jsx یا هر اسمی).
//    - اگه پروژه اصلی بک‌اند سنگین داره و به سرور وصله (مثلاً پایتون/جنگو/فلسک)،
//      نیازی نیست اون بک‌اند رو اینجا پیاده کنی. فقط UI رو با داده‌ی نمونه (mock data)
//      بازسازی کن، دقیقاً مثل CafeProject که سفارش واقعی به هیچ سروری نمی‌فرسته.
//    - اگه پروژه داده‌های حساس داره (مثلاً پروفایل مشتری‌ها)، اونا رو نشون نده -
//      فقط بخش‌های عمومی سایت (مثل ویترین محصولات) رو بازسازی کن.
//      نمونه: project-2/Project2.jsx یه فروشگاه آنلاینه که فقط ویترین محصولات
//      و سبد خرید (نمایشی، بدون ثبت واقعی) رو نشون می‌ده.
//
// ۳. یه خط این‌جا اضافه کن که کلید (slug) رو به کامپوننتت وصل کنه:
//    'project-3': lazy(() => import('./project-3/YourComponent')),
//
// ۴. توی src/utils/projectsData.js یه آیتم جدید برای پروژه اضافه کن با:
//    demo: '/projects/project-3', isInternal: true
//
// همین! پروژه هم توی صفحه نمونه‌کارها لیست می‌شه، هم با کلیک روی "مشاهده پروژه"
// مستقیم توی همین سایت باز می‌شه - دقیقاً مثل کافه گاف.

export const projectDemos = {
  cafe: lazy(() => import('./cafe/CafeProject')),
  'project-2': lazy(() => import('./project-2/Project2')),
  'project-3': lazy(() => import('./project-3/shop')),
};
